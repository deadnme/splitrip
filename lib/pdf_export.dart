import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import 'db.dart';
import 'format.dart';
import 'screens/expense_form_screen.dart' show categories;
import 'screens/trip_screen.dart';

/// Trip summary PDF, handed to the system share sheet.
// ponytail: built-in Helvetica covers Latin-1 only, so amounts use ISO codes
// ("PHP 1,234.50") and non-Latin names won't render. Embed a TTF font if needed.
Future<void> exportPdf(TripData d) async {
  try {
    final t = d.trip!;
    const muted = pw.TextStyle(fontSize: 7, color: PdfColors.grey600);
    // Same as the app: whole number in front, exact value small underneath.
    pw.Widget amt(int v, Rounding r, [String prefix = '']) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.end,
          mainAxisSize: pw.MainAxisSize.min,
          children: [
            pw.Text('$prefix${formatWhole(v, t.currency, r, code: true)}'),
            if (!isWhole(v, t.currency)) pw.Text(formatMoney(v, t.currency, code: true), style: muted),
          ],
        );
    final bal = d.shownBalances;
    final transfers = d.transfers;
    final total = d.expenses.fold<int>(0, (s, e) => s + e.amount);
    const head = pw.TextStyle(fontWeight: pw.FontWeight.bold);
    const right = {4: pw.Alignment.centerRight};
    final doc = pw.Document()
      ..addPage(pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        footer: (c) => pw.Align(
          alignment: pw.Alignment.center,
          child: pw.Text('Generated by SpliTrip', style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey)),
        ),
        build: (c) => [
          pw.Header(level: 0, text: t.name),
          pw.RichText(
            text: pw.TextSpan(children: [
              pw.TextSpan(text: 'Total spent: ${formatWhole(total, t.currency, Rounding.nearest, code: true)}'),
              if (!isWhole(total, t.currency)) pw.TextSpan(text: '  (${formatMoney(total, t.currency, code: true)})', style: muted),
              pw.TextSpan(text: '   ·   ${d.expenses.length} expenses   ·   ${d.people.length} people'),
            ]),
          ),
          pw.SizedBox(height: 16),
          pw.Text('Expenses', style: head),
          pw.TableHelper.fromTextArray(
            headers: ['Date', 'Title', 'Paid by', 'Category', 'Amount'],
            cellAlignments: right,
            data: [
              for (final e in d.expenses)
                [e.date, e.title, d.name(e.paidBy), categories[e.category] ?? e.category, amt(e.amount, Rounding.nearest)],
            ],
          ),
          pw.SizedBox(height: 16),
          pw.Text('Balances', style: head),
          pw.TableHelper.fromTextArray(
            headers: ['Person', 'Balance'],
            cellAlignments: {1: pw.Alignment.centerRight},
            data: [
              for (final e in bal.entries)
                [
                  d.name(e.key),
                  // Owes rounds up, gets back rounds down.
                  e.value > 0
                      ? amt(e.value, Rounding.down, 'gets back ')
                      : e.value < 0
                          ? amt(-e.value, Rounding.up, 'owes ')
                          : 'settled',
                ],
            ],
          ),
          pw.SizedBox(height: 16),
          pw.Text('Suggested transfers', style: head),
          if (transfers.isEmpty) pw.Text('Everyone is settled up.'),
          if (transfers.isNotEmpty)
            pw.TableHelper.fromTextArray(
              headers: ['From', 'To', 'Amount'],
              cellAlignments: {2: pw.Alignment.centerRight},
              data: [for (final x in transfers) [d.name(x.from), d.name(x.to), amt(x.amount, Rounding.up)]],
            ),
        ],
      ));
    final file = '${t.name.replaceAll(RegExp(r'[^A-Za-z0-9]+'), '_')}_summary.pdf';
    await Printing.sharePdf(bytes: await doc.save(), filename: file);
  } catch (e) {
    showError('PDF export failed: $e');
  }
}
